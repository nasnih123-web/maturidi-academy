/**
 * NOTE: `fa` is intentionally NOT `as const` — it is the structural source
 * of truth and `ar`/`en` are checked against `typeof fa` (same keys, any
 * string values). Literal types would force all three locales to carry
 * identical Persian strings.
 */

export type StringKey = keyof typeof fa;
export type NestedKey<T> = T extends object
  ? { [K in keyof T]: K extends string ? (T[K] extends object ? `${K}.${NestedKey<T[K]>}` : K) : never }[keyof T]
  : never;

export type I18nKey = NestedKey<typeof fa>;

