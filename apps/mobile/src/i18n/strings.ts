const catalogs: Record<Locale, typeof fa> = { fa, ar, en };

function lookup(obj: unknown, path: string): string {
  const parts = path.split(".");
  let cur: unknown = obj;
  for (const p of parts) {
    if (cur == null || typeof cur !== "object") return path;
    cur = (cur as Record<string, unknown>)[p];
  }
  return typeof cur === "string" ? cur : path;
}

/** Localised string for the given key and locale (fa fallback). */
export function t(key: I18nKey, locale: Locale = "fa"): string {
  const hit = lookup(catalogs[locale], key);
  if (hit !== key) return hit;
  return lookup(catalogs.fa, key);
}

